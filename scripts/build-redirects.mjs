// Writes Netlify's _redirects file from tools.json, so every tool gets a short,
// stable link (https://<site>/<slug>) that is safe to paste into Canvas.
// Netlify runs this on every push (see netlify.toml).
import { readFileSync, writeFileSync } from "node:fs";

const { tools } = JSON.parse(readFileSync("tools.json", "utf8"));
const lines = ["# Generated by scripts/build-redirects.mjs from tools.json. Do not edit by hand."];

for (const t of tools) {
  if (t.path) { // games and browser apps hosted on this site
    lines.push(`/${t.slug}  /${t.path}  301`);
  } else if (t.url) {
    lines.push(`/${t.slug}  ${t.url}  302`);
  } else {
    lines.push(`/${t.slug}  /  302`);
  }
  if (t.guide) lines.push(`/${t.slug}/guide  /${t.guide}  301`);
}

lines.push("/sources  /citations/  301");

writeFileSync("_redirects", lines.join("\n") + "\n");
console.log(`Wrote _redirects with ${tools.length} tools.`);
